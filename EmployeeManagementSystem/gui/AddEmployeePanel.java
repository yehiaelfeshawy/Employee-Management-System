    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed
              try {
            if (manager == null) {
                throw new IllegalStateException("The form is not connected to the Employee Manager.");
            }
            String name = nameField.getText().trim();
            String position = positionField.getText().trim();
            if (name.isEmpty() || position.isEmpty()) {
                throw new IllegalArgumentException("Name and Position are required.");
            }

            int employeeId = parsePositiveInt(idField.getText(), "Employee ID");
            int age = parsePositiveInt(ageField.getText(), "Age");

            Department dept = (Department) departmentBox.getSelectedItem();
            if (dept == null) {
                throw new IllegalArgumentException("Please select a department.");
            }

            if (manager.searchById(employeeId) != null) {
                throw new IllegalArgumentException("Employee ID " + employeeId + " already exists.");
            }

            String type = (String) typeBox.getSelectedItem();
            Employee emp;
            if ("Full-Time".equals(type)) {
                double basicSalary = parseNonNegative(basicSalaryField.getText(), "Basic Salary");
                double bonus = parseNonNegative(bonusField.getText(), "Bonus");
                emp = new FullTimeEmployee(employeeId, name, age, dept, position, basicSalary, bonus);
            } else if ("Part-Time".equals(type)) {
                double hourlyRate = parseNonNegative(hourlyRateField.getText(), "Hourly Rate");
                double hoursWorked = parseNonNegative(hoursWorkedField.getText(), "Hours Worked");
                emp = new PartTimeEmployee(employeeId, name, age, dept, position, hourlyRate, hoursWorked);
            } else {
                throw new IllegalArgumentException("Please select a valid employee type.");
            }

            if (manager.addEmployee(emp)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Employee added successfully!");
                clearForm();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "The employee could not be added (duplicate ID or invalid department).",
                        "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        } catch (IllegalArgumentException | IllegalStateException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(), "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        } // TODO add your handling code here:
    }//GEN-LAST:event_addButtonActionPerformed

