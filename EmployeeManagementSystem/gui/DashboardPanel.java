    private void searchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchButtonActionPerformed
              String text = searchField.getText().trim();
        String type = (String) searchTypeBox.getSelectedItem();

        if (text.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a search value.",
                    "Search", JOptionPane.WARNING_MESSAGE);
            return;
        }

        List<Employee> result;
        if ("ID".equals(type)) {
            int id;
            try {
                id = Integer.parseInt(text);
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(this, "Employee ID must be a valid integer.",
                        "Search", JOptionPane.ERROR_MESSAGE);
                return;
            }
            result = new ArrayList<>();
            Employee found = manager.searchById(id);
            if (found != null) {
                result.add(found);
            }
        } else if ("Name".equals(type)) {
            result = manager.searchByName(text);
        } else {
            result = manager.filterByDepartment(text);
        }

        fillTable(result);
        if (result.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No employees found.",
                    "Search", JOptionPane.INFORMATION_MESSAGE);
        }  // TODO add your handling code here:
    }//GEN-LAST:event_searchButtonActionPerformed

