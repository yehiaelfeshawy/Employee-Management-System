    private void fillTable(List<Employee> list) {
        tableModel.setRowCount(0);
        for (Employee e : list) {
            String dept = e.getDepartment() != null ? e.getDepartment().getDepartmentName() : "";
            tableModel.addRow(new Object[]{
                e.getEmployeeId(), e.getFullName(), e.getAge(),
                dept, e.getPosition(), e.getEmployeeType(), e.calculateSalary()
            });
        }
    }

