    private void deleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteButtonActionPerformed
               int row = employeesTable.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Please select an employee to delete.",
                    "Delete", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int id = (int) tableModel.getValueAt(row, 0);
        String name = String.valueOf(tableModel.getValueAt(row, 1));

        int choice = JOptionPane.showConfirmDialog(this,
                "Delete employee " + name + " (ID " + id + ")?",
                "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (choice != JOptionPane.YES_OPTION) {
            return;
        }

        if (manager.deleteEmployee(id)) {
            JOptionPane.showMessageDialog(this, "Employee deleted successfully.");
            searchField.setText("");
            refreshData();
        } else {
            JOptionPane.showMessageDialog(this, "The employee could not be deleted.",
                    "Delete", JOptionPane.ERROR_MESSAGE);
        } // TODO add your handling code here:
    }//GEN-LAST:event_deleteButtonActionPerformed


