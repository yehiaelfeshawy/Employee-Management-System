    /**
     * Creates new form MainFrame
     */
    private final EmployeeManager manager;
    private final CardLayout cards;
 
    private final DashboardPanel dashboardPanel;
    private final AddEmployeePanel addEmployeePanel;
    private final ViewUpdatePanel viewUpdatePanel;
    private final DepartmentPanel departmentPanel;
 
    public MainFrame(EmployeeManager manager) {
        this.manager = manager;
        initComponents();
        setTitle("Employee Management System");
        setLocationRelativeTo(null);
 
        cards = (CardLayout) getContentPane().getLayout();
 
        dashboardPanel = new DashboardPanel(manager, this);
        addEmployeePanel = new AddEmployeePanel(manager, () -> showPanel("DASHBOARD"));
        viewUpdatePanel = new ViewUpdatePanel(manager, this);
        departmentPanel = new DepartmentPanel(manager, this);
 
        getContentPane().add(new LoginPanel(this), "LOGIN");
        getContentPane().add(dashboardPanel, "DASHBOARD");
        getContentPane().add(addEmployeePanel, "ADD_EMPLOYEE");
        getContentPane().add(viewUpdatePanel, "VIEW_UPDATE");
        getContentPane().add(departmentPanel, "DEPARTMENT");
 
        showPanel("LOGIN");
    }
    
    public void showPanel(String name) {
        switch (name) {
            case "DASHBOARD":    dashboardPanel.refreshData();    break;
            case "ADD_EMPLOYEE": addEmployeePanel.refreshData();  break;
            case "VIEW_UPDATE":  viewUpdatePanel.refreshData();   break;
            case "DEPARTMENT":   departmentPanel.refreshData();   break;
            default: break;
        }
        cards.show(getContentPane(), name);
    }

