    private void populateDepartments() {

    deptComboBox.removeAllItems();

    if (manager.getDepartments() != null) {
        for (Department d : manager.getDepartments()) {
            deptComboBox.addItem(d.getDepartmentName());
        }
    }
    }
    
private void loadSelectedRowIntoForm() {
    int row = employeeTable.getSelectedRow();

    if (row < 0 || manager == null) {
        clearForm();
        return;
    }

    int empId = (int) tableModel.getValueAt(row, 0);
    Employee emp = manager.searchById(empId);

    if (emp == null) {
        clearForm();
        return;
    }

    selectedOriginalId = emp.getEmployeeId();

    idField.setText(String.valueOf(emp.getEmployeeId()));
    nameField.setText(emp.getFullName());
    ageField.setText(String.valueOf(emp.getAge()));
    positionField.setText(emp.getPosition());

    deptComboBox.setSelectedItem(emp.getDepartment().getDepartmentName());

    if (emp instanceof PartTimeEmployee) {
        PartTimeEmployee pt = (PartTimeEmployee) emp;

        isPartTimeSelected = true;
        typeValueLabel.setText("Part-Time");

        setPayFieldsVisible(false, true);

        hourlyRateField.setText(String.valueOf(pt.getHourlyRate()));
        hoursWorkedField.setText(String.valueOf(pt.getHoursWorked()));

        basicSalaryField.setText("");
        bonusField.setText("");

    } else if (emp instanceof FullTimeEmployee) {
        FullTimeEmployee ft = (FullTimeEmployee) emp;

        isPartTimeSelected = false;
        typeValueLabel.setText("Full-Time");

        setPayFieldsVisible(true, false);

        basicSalaryField.setText(String.valueOf(ft.getBasicSalary()));
        bonusField.setText(String.valueOf(ft.getBonus()));

        hourlyRateField.setText("");
        hoursWorkedField.setText("");
    }
}

private void setPayFieldsVisible(boolean fullTime, boolean partTime) {
    basicSalaryLabel.setVisible(fullTime);
    basicSalaryField.setVisible(fullTime);
    bonusLabel.setVisible(fullTime);
    bonusField.setVisible(fullTime);

    hourlyRateLabel.setVisible(partTime);
    hourlyRateField.setVisible(partTime);
    hoursWorkedLabel.setVisible(partTime);
    hoursWorkedField.setVisible(partTime);

    revalidate();
    repaint();
}

private void clearForm() {
    selectedOriginalId = -1;

    idField.setText("");
    nameField.setText("");
    ageField.setText("");
    positionField.setText("");

    basicSalaryField.setText("");
    bonusField.setText("");
    hourlyRateField.setText("");
    hoursWorkedField.setText("");

    typeValueLabel.setText("-");

    setPayFieldsVisible(false, false);
}

